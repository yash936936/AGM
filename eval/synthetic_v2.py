def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=0, help="first generator seed (default: 0)")
    parser.add_argument("--entities", type=int, default=200)
    parser.add_argument("--episodes", type=int, default=2000, help="number of topic-near-duplicate distractor episodes")
    parser.add_argument("--seeds", type=int, default=5, help="number of seed runs, starting at --seed (default: 5 means seeds 0..4)")
    parser.add_argument("--k", type=int, default=8)
    parser.add_argument("--embedder", choices=("hash", "st"), default="hash")
    parser.add_argument("--results-dir", default=str(ROOT / "eval" / "results"), help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    if args.entities < 5:
        parser.error("--entities must be at least 5 to form relation chains")
    if args.episodes < 0:
        parser.error("--episodes must be non-negative")
    if args.seeds < 1:
        parser.error("--seeds must be at least 1")
    if args.k < 1:
        parser.error("--k must be at least 1")
    try:
        # Fail fast for optional dependencies before constructing any stores/results.
        embedder = make_embedder(args.embedder)
        seed_results = []
        for offset in range(args.seeds):
            current_seed = args.seed + offset
            print(f"Running seed {current_seed} ({offset + 1}/{args.seeds})...", flush=True)
            seed_results.append(evaluate_seed(
                seed=current_seed, entities=args.entities, episodes=args.episodes,
                k=args.k, embedder=embedder,
            ))
            print(f"Finished seed {current_seed}.", flush=True)
    except RuntimeError as exc:
        parser.exit(2, f"error: {exc}\n")

    aggregated = aggregate_seed_metrics(seed_results)
    verdicts = decision_verdicts(aggregated)
    result_dir = Path(args.results_dir)
    result_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ")
    output_path = result_dir / f"{timestamp}.json"
    payload = {
        "schema_version": 2,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "configuration": {
            "seed": args.seed, "seeds": [args.seed + offset for offset in range(args.seeds)],
            "entities": args.entities, "episodes": args.episodes, "k": args.k,
            "embedder": seed_results[0]["embedder_id"],
            "abstain_threshold": ABSTAIN_THRESHOLD, "bootstrap_resamples": BOOTSTRAP_RESAMPLES,
        },
        "decision_rule": verdicts["rule"],
        "aggregate": aggregated,
        "verdicts": verdicts,
        "per_seed": [
            {key: value for key, value in result.items() if key != "query_trace"}
            for result in seed_results
        ],
        "query_trace": [
            {"seed": result["seed"], **row}
            for result in seed_results for row in result["query_trace"]
        ],
        "caveat": "D-007: synthetic smoke-test output is not evidence for or against H1-H7.",
    }
    output_path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print_report(args, seed_results, aggregated, verdicts, output_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
